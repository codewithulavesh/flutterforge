/**
 * Collects the exact files that go into the ZIP:
 * live project files when present, starter files as fallback, always with
 * a unique-id pubspec and a runnable README.
 */
export function collectExportFiles(project: Project, files: ProjectFile[]): ZipFile[] {
  const appId = generateUniqueAppId(project.name, project.id);
  let collected: ZipFile[];

  if (!files.some((file) => !file.is_directory && file.content)) {
    throw new Error('No generated files yet. Generate the app first, then export.');
  }
  collected = files
    .filter((file) => !file.is_directory && file.content)
    .map((file) => ({ path: file.path, content: file.content }));

  const hasPubspec = collected.some((f) => f.path === 'pubspec.yaml');
  if (!hasPubspec) {
    const fallback = generateFlutterProjectFiles(
      project.name,
      project.template,
      [],
      DEFAULT_THEME,
      project.id,
    ).find((f) => f.path === 'pubspec.yaml');
    if (fallback?.content) {
      collected = [...collected, { path: 'pubspec.yaml', content: fallback.content }];
    }
  }

  if (!collected.some((f) => f.path === 'README.md')) {
    collected = [...collected, { path: 'README.md', content: buildExportReadme(project, appId) }];
  }

  // Flutter platform runners are standard scaffolding, not app code. Add a
  // one-command helper for the selected target instead of shipping stale
  // platform boilerplate. Web also gets a minimal runner so `flutter build web`
  // works even though the generation engine writes Dart only.
  const platform = String(project.platform || 'web').toLowerCase();
  const defaultTargets = platform === 'mobile'
    ? 'android,ios'
    : platform === 'desktop'
      ? 'macos,windows'
      : platform === 'macos' || platform === 'windows'
        ? platform
        : 'web';

  if (defaultTargets.split(',').includes('web') && !collected.some((f) => f.path === 'web/index.html')) {
    collected = [...collected, {
      path: 'web/index.html',
      content: [
        '<!DOCTYPE html>',
        '<html>',
        '<head>',
        '  <base href="$FLUTTER_BASE_HREF">',
        '  <meta charset="UTF-8">',
        '  <meta name="viewport" content="width=device-width, initial-scale=1.0">',
        `  <meta name="description" content="${project.name} — built with FlutterForge">`,
        `  <title>${project.name}</title>`,
        '</head>',
        '<body>',
        '  <script src="flutter_bootstrap.js" async></script>',
        '</body>',
        '</html>',
        '',
      ].join('\n'),
    }];
  }

  if (!collected.some((f) => f.path === 'tool/create_platforms.sh')) {
    collected = [...collected, {
      path: 'tool/create_platforms.sh',
      content: [
        '#!/usr/bin/env bash',
        'set -euo pipefail',
        '# Adds the standard Flutter runner folders for the selected targets',
        '# without overwriting lib/, pubspec.yaml, or existing platform folders.',
        `TARGETS="${'${1:-'}${defaultTargets}}"`,
        'flutter create --platforms="$TARGETS" .',
        'flutter pub get',
        'echo "Added: $TARGETS. Run: flutter run -d <device>"',
        '',
      ].join('\n'),
    }];
    collected = [...collected, {
      path: 'tool/create_platforms.ps1',
      content: [
        `param([string]$Targets = "${defaultTargets}")`,
        '$ErrorActionPreference = "Stop"',
        '# Adds the standard Flutter runner folders for the selected targets.',
        'flutter create --platforms=$Targets .',
        'flutter pub get',
        'Write-Host "Added: $Targets. Run: flutter run -d <device>"',
        '',
      ].join('\n'),
    }];
  }

  // Deterministic order for stable, reviewable ZIPs.
  return collected.sort((x, y) => x.path.localeCompare(y.path));
}

/** Builds the ZIP blob without triggering a download (for previews/tests). */
export async function buildProjectZip(project: Project, files: ProjectFile[]): Promise<BuiltZip> {
  const { default: JSZip } = await loadJSZip();
  const appId = generateUniqueAppId(project.name, project.id);
  const collected = collectExportFiles(project, files);
  const zip = new JSZip();
  for (const file of collected) {
    zip.file(file.path, file.content);
  }
  const blob = await zip.generateAsync({ type: 'blob', compression: 'DEFLATE' });
  return {
    blob,
    filename: `${appId}.zip`,
    appId,
    fileCount: collected.length,
    bytes: blob.size,
  };
}

/** Triggers a browser download for a blob with proper cleanup. */
export function downloadBlob(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  anchor.rel = 'noopener';
  document.body.appendChild(anchor);
  anchor.click();
  anchor.remove();
  // Revoke lazily — immediate revocation can abort large downloads.
  window.setTimeout(() => URL.revokeObjectURL(url), 10_000);
}

/**
 * One-click download for an open project (workspace / export view).
 * Throws on failure so callers can toast the real error.
 */
export async function downloadProjectZip(project: Project, files: ProjectFile[]): Promise<BuiltZip> {
  const built = await buildProjectZip(project, files);
  downloadBlob(built.blob, built.filename);
  return built;
}

/**
 * One-click download from anywhere (dashboard cards): fetches the project's
 * files first, falls back to starter files when offline/unconfigured.
 * Throws on failure so callers can toast the real error.
 */
export async function downloadProjectById(project: Project): Promise<BuiltZip> {
  let files: ProjectFile[] = [];
  if (isSupabaseConfigured) {
    const { data } = await supabase
      .from('project_files')
      .select('*')
      .eq('project_id', project.id)
      .order('path', { ascending: true });
    files = (data as ProjectFile[]) ?? [];
  }
  return downloadProjectZip(project, files);
}

/** Human-readable byte size for export confirmations. */
export function formatBytes(bytes: number): string {
  if (!Number.isFinite(bytes) || bytes < 0) return '0 B';
  if (bytes < 1024) return `${bytes} B`;
  const units = ['KB', 'MB', 'GB'];
  let value = bytes / 1024;
  let unit = 0;
  while (value >= 1024 && unit < units.length - 1) {
    value /= 1024;
    unit++;
  }
  return `${value.toFixed(value >= 100 ? 0 : 1)} ${units[unit]}`;
}
