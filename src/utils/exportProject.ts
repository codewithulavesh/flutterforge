import type { Project, ProjectFile } from '../types';
import { supabase, isSupabaseConfigured } from '../services/supabase';
import { generateFlutterProjectFiles, DEFAULT_THEME } from './flutterTemplates';
import { generateUniqueAppId } from './appId';

export interface BuiltZip {
  blob: Blob;
  filename: string;
  appId: string;
  fileCount: number;
  bytes: number;
}

type ZipFile = { path: string; content: string };

async function loadJSZip() {
  return import('jszip');
}

