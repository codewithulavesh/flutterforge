import test from 'node:test';
import assert from 'node:assert/strict';
import { buildProfilePatch, findDshRuntime, resolveModelRoute } from '../harness/dsh.js';

test('OpenRouter keys route through the pi-ai provider', () => {
  const route = resolveModelRoute({ apiKey: 'sk-or-v1-test', model: 'nvidia/nemotron-3-ultra-550b-a55b:free' });
  assert.equal(route.provider, 'openrouter');
  assert.equal(route.model, 'nvidia/nemotron-3-ultra-550b-a55b:free');
  assert.equal(route.apiKeyEnv, 'OPENROUTER_API_KEY');
});

test('native DeepSeek keys never receive an OpenRouter model id', () => {
  const route = resolveModelRoute({ apiKey: 'sk-deepseek-test', model: 'nvidia/nemotron-3-ultra-550b-a55b:free' });
  assert.equal(route.provider, 'deepseek-official');
  assert.equal(route.model, 'deepseek-flash');
  assert.equal(route.apiKeyEnv, 'DEEPSEEK_API_KEY');
});

test('no key still selects the signed-in DeepSeek route', () => {
  const route = resolveModelRoute({ apiKey: '', model: '' });
  assert.equal(route.provider, 'deepseek-account');
  assert.equal(route.model, 'deepseek-flash');
});

test('DSH_BIN overrides runtime discovery', () => {
  const previous = process.env.DSH_BIN;
  process.env.DSH_BIN = process.execPath;
  try {
    assert.equal(findDshRuntime(), process.execPath);
  } finally {
    if (previous === undefined) delete process.env.DSH_BIN;
    else process.env.DSH_BIN = previous;
  }
});

test('the generated profile enables both credential and OpenRouter routes', () => {
  const patch = buildProfilePatch();
  assert.match(patch, /Generated by FlutterForge/);
  assert.match(patch, /id: llm-pi-ai/);
  assert.match(patch, /apiKeyEnv: OPENROUTER_API_KEY/);
  assert.match(patch, /id: agent-default-model/);
});

