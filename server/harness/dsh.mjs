import { spawn } from 'node:child_process';
import { existsSync, promises as fs } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import readline from 'node:readline';
import { findFlutter } from './flutter.mjs';

const IS_WINDOWS = process.platform === 'win32';
const DEFAULT_PROFILE = 'flutterforge-engine';
const DEFAULT_OPENROUTER_MODEL = 'nvidia/nemotron-3.5-lightning:free';
const DEFAULT_DEEPSEEK_MODEL = 'deepseek-flash';
const DEFAULT_TIMEOUT_MS = 20 * 60 * 1000;
const PROFILE_PATCH_MARKER = 'Generated by FlutterForge';

/** @typedef {{ ok: boolean, code: number | null, stdout: string, stderr: string, timedOut?: boolean }} CommandResult */

/**
 * Run a command and capture bounded output.
 * @param {string} command
 * @param {string[]} args
 * @param {{ cwd?: string, env?: NodeJS.ProcessEnv, timeoutMs?: number }} [options]
 * @returns {Promise<CommandResult>}
 */
export function runCommand(command, args, options = {}) {
  const { cwd, env, timeoutMs = 20_000 } = options;
  return new Promise((resolve) => {
    let settled = false;
    let child;
    try {
      child = spawn(command, args, {
        cwd,
        env: env ?? process.env,
        shell: IS_WINDOWS,
        stdio: ['ignore', 'pipe', 'pipe'],
      });
    } catch (error) {
      resolve({ ok: false, code: null, stdout: '', stderr: error instanceof Error ? error.message : String(error) });
      return;
    }

    let stdout = '';
    let stderr = '';
    const timer = setTimeout(() => {
      if (settled) return;
      settled = true;
      try {
        child.kill('SIGKILL');
      } catch {
        // already gone
      }
      resolve({ ok: false, code: null, stdout, stderr: `${stderr}\nTimed out after ${timeoutMs}ms`, timedOut: true });
    }, timeoutMs);

    child.stdout?.on('data', (chunk) => {
      stdout = `${stdout}${chunk}`.slice(-32_768);
    });
    child.stderr?.on('data', (chunk) => {
      stderr = `${stderr}${chunk}`.slice(-32_768);
    });
    child.on('error', (error) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      resolve({ ok: false, code: null, stdout, stderr: `${stderr}\n${error.message}`.trim() });
    });
    child.on('close', (code) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      resolve({ ok: code === 0, code, stdout: stdout.trim(), stderr: stderr.trim() });
    });
  });
}

/**
 * Resolve the DSH runtime. Resolution order mirrors the upstream desktop app:
 * explicit override, bundled runtime, installed app, then PATH.
 * @param {{ env?: NodeJS.ProcessEnv, home?: string }} [options]
 * @returns {string | null}
 */
export function findDshRuntime(options = {}) {
  const env = options.env ?? process.env;
  const home = options.home ?? os.homedir();
  const candidates = [];

  if (env.DSH_BIN) candidates.push(env.DSH_BIN);

  const bundled = process.resourcesPath
    ? path.join(process.resourcesPath, 'dsh', 'bin', IS_WINDOWS ? 'dsh.cmd' : 'dsh')
    : null;
  if (bundled) candidates.push(bundled);
  candidates.push(path.join(process.cwd(), 'runtime', 'cli', 'bin', IS_WINDOWS ? 'dsh.cmd' : 'dsh'));

  if (process.platform === 'darwin') {
    candidates.push(
      '/Applications/DeepSeek Harness.app/Contents/Resources/runtime/cli/bin/dsh',
      path.join(home, 'Applications', 'DeepSeek Harness.app', 'Contents', 'Resources', 'runtime', 'cli', 'bin', 'dsh'),
    );
  } else if (IS_WINDOWS) {
    const localAppData = env.LOCALAPPDATA || path.join(home, 'AppData', 'Local');
    const programFiles = env.ProgramFiles || 'C:\\Program Files';
    candidates.push(
      path.join(localAppData, 'Programs', 'DeepSeek Harness', 'resources', 'runtime', 'cli', 'bin', 'dsh.cmd'),
      path.join(localAppData, 'DeepSeek Harness', 'resources', 'runtime', 'cli', 'bin', 'dsh.cmd'),
      path.join(programFiles, 'DeepSeek Harness', 'resources', 'runtime', 'cli', 'bin', 'dsh.cmd'),
    );
  }

  for (const candidate of candidates) {
    if (!candidate) continue;
    if (candidate === 'dsh' || candidate === 'dsh.cmd') return candidate;
    if (existsSync(candidate)) return candidate;
  }

  // Last resort: let PATH resolve it. `runCommand` reports ENOENT cleanly.
  return 'dsh';
}

/** @type {Promise<{ available: boolean, path: string, version: string | null, error?: string }> | null} */
let cachedRuntimeInfo = null;

/**
 * Detect the runtime and its version once per process.
 * @param {{ refresh?: boolean }} [options]
 */
export function getRuntimeInfo(options = {}) {
  if (cachedRuntimeInfo && !options.refresh) return cachedRuntimeInfo;
  cachedRuntimeInfo = (async () => {
    const dshPath = findDshRuntime();
    if (!dshPath) {
      return { available: false, path: '', version: null, error: 'DeepSeek Harness runtime not found.' };
    }
    const result = await runCommand(dshPath, ['--version'], { timeoutMs: 15_000 });
    const version = (result.stdout || result.stderr).split('\n')[0]?.trim() || null;
    return {
      available: result.ok,
      path: dshPath,
      version,
      ...(result.ok ? {} : { error: result.stderr || 'The harness runtime did not answer --version.' }),
    };
  })();
  return cachedRuntimeInfo;
}

/** @returns {string} */
export function getDshHome() {
  return process.env.DSH_HOME || path.join(os.homedir(), '.dsh');
}

/** @returns {string} */
export function getProfileName() {
  return process.env.FLUTTERFORGE_DSH_PROFILE || DEFAULT_PROFILE;
}

/** @returns {string} */
export function getProfileDir() {
  return path.join(getDshHome(), 'profiles', getProfileName());
}

/**
 * Decide whether a request key is an OpenRouter key (which routes through the
 * built-in pi-ai adapter) or a native DeepSeek key (the default route).
 * @param {{ apiKey?: string, model?: string }} input
 */
export function resolveModelRoute(input) {
  const apiKey = (input.apiKey ?? '').trim();
  const requestedModel = (input.model ?? '').trim();
  const openRouter = apiKey.startsWith('sk-or-') || (!apiKey && requestedModel.includes('/'));
  // With no launch key the signed-in DeepSeek account route is the only
  // credential source; a real DEEPSEEK_API_KEY switches to the API-key route.
  const managedAccount = !openRouter && !apiKey && !process.env.DEEPSEEK_API_KEY;
  // An OpenRouter model id contains a slash; sending one to the DeepSeek
  // route would fail with UNKNOWN_MODEL, so fall back to the native default.
  const requestedForRoute = !openRouter && requestedModel.includes('/') ? '' : requestedModel;
  const model = sanitizeModelId(
    requestedForRoute || (openRouter ? DEFAULT_OPENROUTER_MODEL : DEFAULT_DEEPSEEK_MODEL),
    openRouter ? DEFAULT_OPENROUTER_MODEL : DEFAULT_DEEPSEEK_MODEL,
  );
  return {
    provider: openRouter ? 'openrouter' : (managedAccount ? 'deepseek-account' : 'deepseek-official'),
    model,
    apiKeyEnv: openRouter ? 'OPENROUTER_API_KEY' : 'DEEPSEEK_API_KEY',
  };
}

/** @param {string} value @param {string} fallback */
function sanitizeModelId(value, fallback) {
  const trimmed = value.trim();
  if (!trimmed || trimmed.length > 160) return fallback;
  if (!/^[A-Za-z0-9._:/+-]+$/.test(trimmed)) return fallback;
  return trimmed;
}

/**
 * The profile patch layers FlutterForge's engine configuration over the
 * headless bundle. It is intentionally a dedicated profile (not the user's
 * `flutterforge` UI profile) so the two never fight over settings.
 * @returns {string}
 */
export function buildProfilePatch() {
  return `# ${PROFILE_PATCH_MARKER} — do not edit by hand.
# Dedicated one-shot engine profile: DeepSeek headless + OpenRouter route.
- id: credentials
  disabled: false
- id: authorization
  disabled: false
- id: deepseek-account
  disabled: false

# OpenRouter is reached through the bundled pi-ai adapter. The key is resolved
# from OPENROUTER_API_KEY per request; no secret is written to this file.
- id: llm-pi-ai
  disabled: false
  config:
    providers:
      openrouter:
        displayName: OpenRouter
        apiKeyEnv: OPENROUTER_API_KEY
        api: openai-completions
        baseURL: https://openrouter.ai/api/v1
        models:
          - id: !!js process.env.FLUTTERFORGE_MODEL || '${DEFAULT_OPENROUTER_MODEL}'
            name: FlutterForge engine model
            contextWindow: 131072
            maxTokens: 16384

- id: agent-default-model
  config:
    provider: !!js process.env.FLUTTERFORGE_PROVIDER || 'deepseek-official'
    model: !!js process.env.FLUTTERFORGE_MODEL || '${DEFAULT_DEEPSEEK_MODEL}'
    # Fast default; a quality retry can override via the request.
    reasoningEffort: !!js process.env.FLUTTERFORGE_REASONING || 'low'
`;
}

/** @type {Map<string, Promise<void>>} */
const profileLocks = new Map();

/**
 * Ensure the dedicated engine profile exists and carries our patch.
 * @param {{ runtime?: string }} [options]
 * @returns {Promise<{ profileDir: string, dshHome: string, profile: string, created: boolean }>}
 */
export async function ensureProfile(options = {}) {
  const dshHome = getDshHome();
  const profile = getProfileName();
  const profileDir = path.join(dshHome, 'profiles', profile);
  const lockKey = `${dshHome}\0${profile}`;

  const existing = profileLocks.get(lockKey);
  if (existing) await existing;

  const task = (async () => {
    const runtime = options.runtime || (await getRuntimeInfo()).path;
    const exists = existsSync(path.join(profileDir, 'cordis.yml'))
      && existsSync(path.join(profileDir, 'package.json'));

    if (!exists) {
      const env = { ...process.env, DSH_HOME: dshHome };
      const result = await runCommand(
        runtime,
        ['--profile', profile, '--from-default-profile', 'headless', '--dump-config'],
        { env, timeoutMs: 120_000 },
      );
      if (!result.ok) {
        throw new Error(
          `Could not create the harness profile "${profile}": ${result.stderr || result.stdout || 'unknown error'}`,
        );
      }
    }

    const patchFile = path.join(profileDir, 'cordis.patch.yml');
    const patch = buildProfilePatch();
    let current = '';
    try {
      current = await fs.readFile(patchFile, 'utf8');
    } catch {
      // first run
    }
    if (current !== patch) {
      await fs.mkdir(profileDir, { recursive: true });
      await fs.writeFile(patchFile, patch, 'utf8');
    }
    return { profileDir, dshHome, profile, created: !exists };
  })();

  profileLocks.set(lockKey, task.then(() => undefined, () => undefined));
  try {
    return await task;
  } finally {
    profileLocks.delete(lockKey);
  }
}

/**
 * Check whether a Flutter/Dart toolchain is reachable. Cached for 60s so the
 * capabilities endpoint stays cheap.
 */
let flutterCache = { at: 0, value: null };
export async function checkFlutter() {
  if (flutterCache.value && Date.now() - flutterCache.at < 60_000) return flutterCache.value;
  const result = await runCommand(findFlutter(), ['--version'], { timeoutMs: 20_000 });
  const firstLine = (result.stdout || result.stderr).split('\n').map((line) => line.trim()).find(Boolean) || '';
  const value = { available: result.ok, version: result.ok ? firstLine : null, error: result.ok ? undefined : firstLine || 'Flutter not found on PATH.' };
  flutterCache = { at: Date.now(), value };
  return value;
}

/**
 * Spawn `dsh headless --json` and stream parsed NDJSON events.
 *
 * Yields every JSON event from the runtime plus a terminal `exit` event. The
 * caller decides how to project them into UI events.
 *
 * @param {object} input
 * @param {string} input.cwd
 * @param {string} input.prompt
 * @param {string} [input.sessionId]
 * @param {string} [input.apiKey]
 * @param {string} [input.model]
 * @param {AbortSignal} [input.signal]
 * @returns {AsyncGenerator<Record<string, any>, void, void>}
 */
export async function* runHarness(input) {
  const runtime = await getRuntimeInfo();
  if (!runtime.available) {
    throw new Error(runtime.error || 'DeepSeek Harness runtime is unavailable.');
  }
  const profile = await ensureProfile({ runtime: runtime.path });
  const route = resolveModelRoute({ apiKey: input.apiKey, model: input.model });
  const timeoutMs = Number(process.env.FLUTTERFORGE_HARNESS_TIMEOUT_MS || DEFAULT_TIMEOUT_MS);

  const env = {
    ...process.env,
    DSH_HOME: profile.dshHome,
    FLUTTERFORGE_PROVIDER: route.provider,
    FLUTTERFORGE_MODEL: route.model,
    FLUTTERFORGE_HARNESS: '1',
    // Headless reads launch-time credentials. Never leak a key into args/logs.
    ...(route.apiKeyEnv === 'OPENROUTER_API_KEY' && input.apiKey
      ? { OPENROUTER_API_KEY: input.apiKey }
      : {}),
    ...(route.apiKeyEnv === 'DEEPSEEK_API_KEY' && input.apiKey
      ? { DEEPSEEK_API_KEY: input.apiKey }
      : {}),
  };

  const args = [
    '--profile',
    profile.profile,
    '--json',
    ...(input.sessionId ? ['--session-id', input.sessionId] : []),
    '-',
  ];

  const child = spawn(runtime.path, args, {
    cwd: input.cwd,
    env,
    shell: IS_WINDOWS,
    stdio: ['pipe', 'pipe', 'pipe'],
  });

  let stderr = '';
  let killedByTimeout = false;
  let killedByAbort = false;
  let exitCode = null;
  let settled = false;

  const kill = (reason) => {
    if (settled) return;
    try {
      child.kill('SIGTERM');
    } catch {
      // already gone
    }
  };

  const timer = setTimeout(() => {
    killedByTimeout = true;
    kill('timeout');
  }, timeoutMs);

  const onAbort = () => {
    killedByAbort = true;
    kill('abort');
  };
  if (input.signal) {
    if (input.signal.aborted) onAbort();
    else input.signal.addEventListener('abort', onAbort, { once: true });
  }

  child.stderr?.on('data', (chunk) => {
    stderr = `${stderr}${chunk}`.slice(-16_384);
  });

  const exitPromise = new Promise((resolve) => {
    child.on('close', (code, signal) => {
      settled = true;
      exitCode = code;
      resolve({ code, signal });
    });
    child.on('error', (error) => {
      stderr = `${stderr}\n${error.message}`.trim();
    });
  });

  // The task is the whole prompt; closing stdin tells the one-shot runner to
  // execute. EPIPE is expected if the runtime exits early.
  try {
    child.stdin.end(input.prompt);
  } catch {
    // handled by the exit event
  }
  child.stdin.on('error', () => {});

  const lines = readline.createInterface({ input: child.stdout, crlfDelay: Infinity });
  try {
    for await (const line of lines) {
      const trimmed = line.trim();
      if (!trimmed) continue;
      try {
        yield JSON.parse(trimmed);
      } catch {
        // A plugin may print a diagnostic to stdout despite the contract;
        // keep it as a text note instead of aborting the stream.
        yield { type: 'diagnostic', text: trimmed };
      }
    }
  } finally {
    // If the consumer stopped early (projection error, client disconnect), the
    // runtime may still be working. Terminate it and bound the wait so a
    // half-closed process can never hang the request.
    if (!settled) {
      try {
        child.kill('SIGTERM');
      } catch {
        // already gone
      }
    }
    const exit = await Promise.race([
      exitPromise,
      new Promise((resolve) => setTimeout(() => {
        if (!settled) {
          try {
            child.kill('SIGKILL');
          } catch {
            // already gone
          }
        }
        resolve({ code: null, signal: 'SIGKILL' });
      }, 5000).unref()),
    ]);
    clearTimeout(timer);
    input.signal?.removeEventListener?.('abort', onAbort);
    yield {
      type: 'exit',
      code: exit.code,
      signal: exit.signal,
      stderr: stderr.trim(),
      timedOut: killedByTimeout,
      aborted: killedByAbort,
    };
  }
}

/**
 * Capability snapshot for the UI. Never creates a profile or spends tokens.
 */
export async function getCapabilities() {
  const [runtime, flutter] = await Promise.all([getRuntimeInfo(), checkFlutter()]);
  const profileDir = getProfileDir();
  const route = resolveModelRoute({ apiKey: process.env.OPENROUTER_API_KEY ? 'sk-or-env' : '', model: process.env.FLUTTERFORGE_MODEL });
  return {
    engine: 'deepseek-harness',
    runtime: {
      available: runtime.available,
      version: runtime.version,
      path: runtime.path || null,
      error: runtime.error,
    },
    profile: {
      name: getProfileName(),
      installed: existsSync(path.join(profileDir, 'cordis.yml')),
      path: profileDir,
    },
    route: { provider: route.provider, model: route.model },
    flutter,
    desktop: {
      macos: process.platform === 'darwin',
      windows: process.platform === 'win32',
    },
    dshHome: getDshHome(),
  };
}
